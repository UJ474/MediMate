// Adaptive intake interview built on Dashavidha Pariksha (the Ayurvedic ten-fold
// examination), with a symptom-led anaemia pathway in front of it.
//
// Patients never see Sanskrit terms: each question is plain language, and the
// `pariksha` tag tells the practitioner dashboard which examination the answer
// feeds. Follow-up questions appear only when an earlier answer calls for them
// (`showIf`), so the next question depends on the previous answer.
//
// Choice answers are stored as the canonical English option (by index), so
// branching and the doctor's view work the same whatever language the patient used.
import type { LangCode } from '../i18n/translations';

type L = Record<LangCode, string>;
type LOptions = Record<LangCode, string[]>;

export type Answers = Record<string, string | string[]>;

export type QuestionType = 'text' | 'mcq' | 'multi_select' | 'measurements';

export type SectionKey = 'complaint' | 'symptoms' | 'bleeding' | 'diet' | 'history' | 'body' | 'closing';

export type Pariksha =
  | 'Prakriti'
  | 'Vikriti'
  | 'Sara'
  | 'Samhanana'
  | 'Pramana'
  | 'Satmya'
  | 'Satva'
  | 'Ahara Shakti'
  | 'Vyayama Shakti'
  | 'Vaya';

export interface IntakeQuestion {
  id: string;
  section: SectionKey;
  pariksha?: Pariksha;
  type: QuestionType;
  text: L;
  options?: LOptions;
  // Patient-record field this answer maps to, where one exists.
  field?: string;
  showIf?: (a: Answers) => boolean;
}

// ---------- helpers ----------
const picked = (a: Answers, id: string, value: string) => {
  const v = a[id];
  return Array.isArray(v) ? v.includes(value) : v === value;
};
const pickedAny = (a: Answers, id: string, values: string[]) => values.some((v) => picked(a, id, v));

