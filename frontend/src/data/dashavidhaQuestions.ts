const BY_ID = new Map(INTAKE_QUESTIONS.map((q) => [q.id, q]));

export function getQuestion(id: string): IntakeQuestion | undefined {
  return BY_ID.get(id);
}

export function isVisible(q: IntakeQuestion, answers: Answers): boolean {
  return !q.showIf || q.showIf(answers);
}

// Index of the next question to ask after `fromIndex`, given the answers so far; -1 when the interview is done.
export function nextQuestionIndex(fromIndex: number, answers: Answers): number {
  for (let i = fromIndex + 1; i < INTAKE_QUESTIONS.length; i++) {
    if (isVisible(INTAKE_QUESTIONS[i], answers)) return i;
  }
  return -1;
}

// Questions the patient will be asked with the current answers (used for the progress estimate).
export function visibleQuestionCount(answers: Answers): number {
  return INTAKE_QUESTIONS.filter((q) => isVisible(q, answers)).length;
}

export function questionText(q: IntakeQuestion, lang: LangCode): string {
  return q.text[lang] || q.text.en;
}

export function questionOptions(q: IntakeQuestion, lang: LangCode): string[] {
  const own = q.options?.[lang];
  return own && own.length === q.options?.en.length ? own : (q.options?.en ?? []);
}

export function sectionTitle(section: SectionKey, lang: LangCode): string {
  return SECTION_TITLES[section][lang] || SECTION_TITLES[section].en;
}

// ---------- stored record ----------
export const SKIPPED = 'Skipped';

export function formatMeasurements(heightCm: number, weightKg: number): string {
  const bmi = weightKg / (heightCm / 100) ** 2;
  return `Height ${heightCm} cm, weight ${weightKg} kg (BMI ${bmi.toFixed(1)})`;
}

// Items the practitioner must look at personally rather than having them interpreted automatically.
export function reviewFlags(answers: Answers): string[] {
  const flags: string[] = [];
  if (picked(answers, 'B1', 'Blood in stool')) flags.push('Blood in stool reported — possible GI blood loss. Practitioner review required.');
  if (picked(answers, 'B1', 'Blood in urine')) flags.push('Blood in urine reported. Practitioner review required.');
  if (picked(answers, 'S4', 'Yes')) flags.push('Palpitations at rest reported.');
  if (picked(answers, 'B3', 'Every 1–2 hours')) flags.push('Heavy menstrual loss (pad change every 1–2 hours on heaviest day).');
  return flags;
}

export function buildIntakeRecord(answers: Answers, languageName: string, date: string): import('../types').IntakeRecord {
  const items = INTAKE_QUESTIONS.filter((q) => answers[q.id] !== undefined && isVisible(q, answers)).map((q) => {
    const value = answers[q.id];
    return {
      id: q.id,
      section: q.section,
      pariksha: q.pariksha,
      question: q.text.en,
      answer: Array.isArray(value) ? value.join(', ') : value,
    };
  });
  return { completedOn: date, language: languageName, answers: items, flags: reviewFlags(answers) };
}

